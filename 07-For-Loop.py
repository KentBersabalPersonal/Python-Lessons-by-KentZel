for i in range(1, 6):
    print("\nCount:", i)

# OUTPUT IS:
# Count: 1
# Count: 2
# Count: 3
# Count: 4
# Count: 5

# MAIN IDEA:
# Python's for loop works differently from C/C++ — instead of manually setting a counter, condition, and increment, it loops through a
# sequence of values using range().
