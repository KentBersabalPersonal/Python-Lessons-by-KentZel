def add(a, b):
    return a + b

result = add(5, 3)
print("\nSum:", result)

# OUTPUT IS:
# Sum: 8

# A function is reusable code that performs a task when called — same
# concept as C/C++, but no return type or prototype needed.

# def add(a, b):   -> "def" defines a function named "add" with two parameters (no need to specify int, float, etc.)
# return a + b      -> sends the result back to wherever it was called
# add(5, 3)         -> calling the function with actual values

# Python doesn't require declaring functions before main() like C/C++ —
# it just needs to be defined BEFORE it's called in the code.

