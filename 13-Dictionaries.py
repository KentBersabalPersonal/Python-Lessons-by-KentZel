student = {
    "name": "Kent",
    "age": 20,
    "grade": 90
}

print("\nName:", student["name"])
print("Age:", student["age"])
print("Grade:", student["grade"])

# OUTPUT IS:
# Name: Kent
# Age: 20
# Grade: 90

# MAIN IDEA:
# A dictionary stores data in key-value pairs, similar to a struct, but
# more flexible — the "keys" work like labels for each piece of data.

# student = { "name": "Kent", ... }
#  -> curly braces {} create the dictionary
#  -> "name" is the KEY, "Kent" is the VALUE
# student["name"]   -> accesses the value using its key (instead of a numbered index like a list).

# More like an object in C++
